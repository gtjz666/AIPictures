def number(value):
    return str(int(value)) if isinstance(value,(int,float)) and not isinstance(value,bool) and value==int(value) else str(value)


def default(field):
    kind=field[2];value=field[3]
    if kind=='bool':return '开启' if value else '关闭'
    if kind=='choice':return str(field[4][value])
    if kind=='asset':return '未选择'
    if kind=='color':return '#'+str(value)
    return number(value)


def requirement(field):
    kind=field[2]
    if kind in ('number','integer'):return number(field[4])+' ～ '+number(field[5])+('；整数' if kind=='integer' else '')
    if kind=='choice':return '／'.join(map(str,field[4].values()))
    if kind=='asset':return {'frames':'项目内角色.tscn／SpriteFrames.tres','image':'项目内图片','audio':'项目内WAV／OGG／MP3','script':'项目内RefCounted GDScript','scene':'项目内2D PackedScene.tscn','module':'项目内子图JSON'}[field[4]]
    return {'bool':'开关','key':'选择常用键或按键捕获','color':'颜色','text':'文字；输入后按回车确认'}[kind]


